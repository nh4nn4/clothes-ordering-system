            function filterProducts(tag) {
                event.preventDefault();

                // Toggle filter if same tag clicked again
                if (currentTagFilter === tag) {
                    currentTagFilter = null;
                    $grid.isotope({ filter: '*' });
                    $('.filter-tagging a').removeClass('hov-tag1').addClass('hov-tag2');
                    return;
                }

                currentTagFilter = tag;
                currentColorFilter = null; // Clear color filter when applying tag filter

                // Update UI
                $('.filter-tagging a').removeClass('hov-tag1').addClass('hov-tag2');
                $(event.currentTarget).removeClass('hov-tag2').addClass('hov-tag1');
                $('.filter-col3 .filter-link').removeClass('filter-link-active');

                // Filter products
                $grid.isotope({
                    filter: function () {
                        const productTags = $(this).attr('data-tags').toLowerCase();
                        return productTags.includes(tag);
                    }
                });
            }

            function showAllProducts() {
                event.preventDefault();
                currentColorFilter = null;
                currentTagFilter = null;

                $grid.isotope({ filter: '*' });
                $('.filter-tagging a').removeClass('hov-tag1').addClass('hov-tag2');
                $('.filter-col3 .filter-link').removeClass('filter-link-active');
                $('.filter-col2 .filter-link[data-price="*"]').addClass('filter-link-active');
            }

            function filterByColor(color) {
                event.preventDefault();

                // Toggle filter if same color clicked again
                if (currentColorFilter === color) {
                    currentColorFilter = null;
                    $grid.isotope({ filter: '*' });
                    $('.filter-col3 .filter-link').removeClass('filter-link-active');
                    return;
                }

                currentColorFilter = color;
                currentTagFilter = null; // Clear tag filter when applying color filter

                // Update UI
                $('.filter-col3 .filter-link').removeClass('filter-link-active');
                $(event.currentTarget).addClass('filter-link-active');
                $('.filter-tagging a').removeClass('hov-tag1').addClass('hov-tag2');

                // Filter products
                $grid.isotope({
                    filter: function () {
                        const colors = $(this).attr('data-colors').toLowerCase().split(',');
                        return colors.includes(color);
                    }
                });
            }


            function clearAllFilters() {
                // Reset Isotope to show all products
                $grid.isotope({
                    filter: '*',
                    sortBy: 'original-order'
                });

                // Remove active classes from all filter links
                $('.filter-link').removeClass('filter-link-active');
                $('.filter-col2 .filter-link[data-price="*"]').addClass('filter-link-active');

                // Remove active classes from tag filters
                $('.filter-tagging a').removeClass('active-tag');

                // Reset any variables tracking active filters
                currentColorFilter = null;

                console.log("All filters cleared");
            }
